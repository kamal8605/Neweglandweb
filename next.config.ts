import type { NextConfig } from "next";
import { PHASE_DEVELOPMENT_SERVER } from "next/constants";
import path from "node:path";

const LOOPBACK_HOSTNAMES = new Set(["localhost", "127.0.0.1", "[::1]"]);

/** The origin of an absolute http(s) URL, or null for anything else. */
function httpOrigin(value: string | undefined): string | null {
  if (!value?.trim()) return null;
  try {
    const url = new URL(value.trim());
    return url.protocol === "https:" || url.protocol === "http:" ? url.origin : null;
  } catch {
    return null;
  }
}

interface SecurityEnv {
  /** NEXT_PUBLIC_API_URL: the API origin the browser talks to. */
  apiUrl?: string;
  /** IMAGE_CDN_URL: an extra image source pattern. */
  imageCdnUrl?: string;
  /** CSP_CONNECT_SRC_EXTRA: extra origins the browser may connect to (space- or comma-separated). */
  extraConnectSrc?: string;
}

/**
 * Image sources for next/image. The loopback API storage hosts are only allowed for local work (the dev server, or a
 * build whose API is itself on this machine); a production build pointed at the real API never fetches loopback URLs.
 */
export function imageRemotePatterns(env: SecurityEnv, dev: boolean): URL[] {
  const apiOrigin = httpOrigin(env.apiUrl);
  const localApi = apiOrigin !== null && LOOPBACK_HOSTNAMES.has(new URL(apiOrigin).hostname);
  return [
    ...(env.imageCdnUrl ? [new URL(env.imageCdnUrl)] : []),
    new URL("https://c8.alamy.com/comp/**"),
    // Production API host (RELEASE_CHECKLIST.md: NEXT_PUBLIC_API_URL)
    new URL("https://hotpink-parrot-228156.hostingersite.com/storage/**"),
    // WebP product image variants generated by the API (see lib/imageVariants.ts)
    new URL("https://hotpink-parrot-228156.hostingersite.com/api/media/**"),
    new URL("https://erp.centralsmokedistro.com/uploads/**"),
    new URL("https://nes-gateway.cloud.bbtl.app/storage/**"),
    ...(dev || localApi
      ? [new URL("http://127.0.0.1:8000/storage/**"), new URL("http://localhost:8000/storage/**")]
      : []),
  ];
}

/**
 * Content-Security-Policy without nonces. Next's inline bootstrap scripts need 'unsafe-inline' unless every page is
 * rendered dynamically with a per-request nonce, which would disable the static/ISR pages this site relies on.
 * The browser may only connect to this site and the API (catalog PDFs are served by the API, see
 * HomepageController::catalogPdf), plus any origins listed in CSP_CONNECT_SRC_EXTRA.
 */
export function contentSecurityPolicy(env: SecurityEnv): string {
  const apiOrigin = httpOrigin(env.apiUrl) ?? "http://localhost:8000"; // same fallback as lib/axios.ts
  const extra = (env.extraConnectSrc ?? "").split(/[\s,]+/).map(httpOrigin).filter((o): o is string => o !== null);
  const connectSrc = [...new Set(["'self'", apiOrigin, ...extra])].join(" ");
  return [
    "default-src 'self'",
    "base-uri 'self'",
    "object-src 'none'",
    "frame-ancestors 'none'",
    "form-action 'self'",
    "script-src 'self' 'unsafe-inline'",
    "style-src 'self' 'unsafe-inline'",
    "font-src 'self' data:",
    "img-src 'self' data: blob: https:",
    `connect-src ${connectSrc}`,
    "worker-src 'self' blob:",
    // Only when the API is HTTPS, so a local build against an http:// API still works.
    ...(apiOrigin.startsWith("https:") ? ["upgrade-insecure-requests"] : []),
  ].join("; ");
}

/** Security headers for every response. The CSP is skipped on the dev server (HMR needs eval and websockets). */
export function securityHeaders(env: SecurityEnv, dev: boolean) {
  return [
    { key: "X-Content-Type-Options", value: "nosniff" },
    { key: "X-Frame-Options", value: "DENY" },
    { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
    { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains; preload" },
    { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), payment=()" },
    ...(dev ? [] : [{ key: "Content-Security-Policy", value: contentSecurityPolicy(env) }]),
  ];
}

export default function nextConfig(phase: string): NextConfig {
  const dev = phase === PHASE_DEVELOPMENT_SERVER;
  const env: SecurityEnv = {
    apiUrl: process.env.NEXT_PUBLIC_API_URL,
    imageCdnUrl: process.env.IMAGE_CDN_URL,
    extraConnectSrc: process.env.CSP_CONNECT_SRC_EXTRA,
  };

  return {
    turbopack: {
      resolveAlias: {
        "pdfjs-dist": "pdfjs-dist/legacy/build/pdf.mjs",
      },
    },
    images: {
      remotePatterns: imageRemotePatterns(env, dev),
      qualities: [75],
    },
    async headers() {
      return [{ source: "/(.*)", headers: securityHeaders(env, dev) }];
    },
    webpack(config) {
      // The modern PDF.js bundle contains its own Webpack runtime and crashes
      // when Next's Webpack compiler processes it. Use PDF.js's compatibility
      // entry while preserving the same React-PDF API.
      config.resolve.alias = {
        ...config.resolve.alias,
        "pdfjs-dist$": path.resolve(
          process.cwd(),
          "node_modules/pdfjs-dist/legacy/build/pdf.mjs",
        ),
      };

      return config;
    },
  };
}
